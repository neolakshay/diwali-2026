export function translate(language, key, values = {}) {
  const text = MESSAGES[language]?.[key] ?? MESSAGES.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (placeholder, name) => String(values[name] ?? placeholder));
}

export function createI18n(root = document) {
  let storage;
  let language = 'en';
  try {
    storage = root.defaultView?.localStorage;
    if (storage?.getItem('diwali-language') === 'hi') language = 'hi';
  } catch { /* Storage can be unavailable in private or embedded browsers. */ }
  const subscribers = new Set();
  const buttons = root.querySelectorAll('[data-language]');
  const t = (key, values) => translate(language, key, values);

  function render() {
    root.documentElement.lang = language;
    root.title = t('pageTitle');
    root.querySelectorAll('[data-i18n]').forEach((element) => {
      element.textContent = t(element.dataset.i18n);
      element.lang = language;
    });
    root.querySelectorAll('[data-i18n-aria]').forEach((element) => {
      element.setAttribute('aria-label', t(element.dataset.i18nAria));
    });
    buttons.forEach((button) => {
      const active = button.dataset.language === language;
      button.setAttribute('aria-pressed', String(active));
      button.classList.toggle('language__active', active);
    });
  }

  function setLanguage(next) {
    if (!Object.hasOwn(MESSAGES, next) || next === language) return;
    language = next;
    try { storage?.setItem('diwali-language', language); } catch { /* Keep the in-page toggle working. */ }
    render();
    subscribers.forEach((callback) => callback(language));
  }

  buttons.forEach((button) => button.addEventListener('click', () => setLanguage(button.dataset.language)));
  render();
  return {
    get language() { return language; },
    t,
    setLanguage,
    subscribe(callback) {
      subscribers.add(callback);
      return () => subscribers.delete(callback);
    },
  };
}
