// Times are seconds on the recording's clock, never independent playback timers.
export function getLyricFrame(time, cues) {
  const index = cues.findIndex((cue) => time >= cue.start && time < cue.end);
  if (index !== -1) return { current: cues[index], next: cues[index + 1] ?? null };
  return { current: null, next: cues.find((cue) => cue.start > time) ?? null };
}
